<?php
/**
 * Test result value object.
 *
 * @package WordPress\AI_Benchmark
 *
 * @phpstan-type StaticDetails array{score: float, checks: array<string, array{passed: bool, weight: float, message?: string}>}
 * @phpstan-type RuntimeDetails array{score: float, checks: array<string, array{passed: bool, message?: string}>}
 * @phpstan-type JudgeDetails array{score: float, criteria_scores?: array<string, float>, feedback?: string}
 */

declare(strict_types=1);

namespace WordPress\AI_Benchmark;

/**
 * Value object representing the result of a single benchmark test.
 *
 * Supports both knowledge tests (simple score) and execution tests
 * (static, runtime, and quality scores).
 */
class Test_Result {

	/**
	 * Test identifier.
	 */
	private string $test_id;

	/**
	 * Test type: 'knowledge' or 'execution'.
	 */
	private string $type;

	/**
	 * Test category (e.g., 'hooks', 'shortcodes').
	 */
	private string $category = '';

	/**
	 * Run number for multi-run benchmarks.
	 */
	private int $run_number = 1;

	/**
	 * Knowledge test score (0.0 or 1.0).
	 */
	private ?float $score = null;

	/**
	 * Model's answer for knowledge tests.
	 */
	private ?string $model_answer = null;

	/**
	 * Correct answer for knowledge tests.
	 */
	private ?string $correct_answer = null;

	/**
	 * Generated code for execution tests.
	 */
	private ?string $generated_code = null;

	/**
	 * Static analysis score (0.0-1.0).
	 */
	private ?float $static_score = null;

	/**
	 * Runtime verification score (0.0-1.0).
	 */
	private ?float $runtime_score = null;

	/**
	 * AI judge quality score (0.0-1.0).
	 */
	private ?float $quality_score = null;

	/**
	 * Detailed static check results.
	 *
	 * @var array<string, mixed>
	 */
	private array $static_details = [];

	/**
	 * Detailed runtime check results.
	 *
	 * @var array<string, mixed>
	 */
	private array $runtime_details = [];

	/**
	 * Detailed AI judge evaluation.
	 *
	 * @var array<string, mixed>
	 */
	private array $judge_details = [];

	/**
	 * Error message if test failed.
	 */
	private ?string $error = null;

	/**
	 * Test duration in milliseconds.
	 */
	private float $duration_ms = 0.0;

	/**
	 * Additional metadata.
	 *
	 * @var array<string, mixed>
	 */
	private array $metadata = [];

	/**
	 * Constructor.
	 *
	 * @param string $test_id Test identifier.
	 * @param string $type    Test type ('knowledge' or 'execution').
	 */
	public function __construct( string $test_id, string $type ) {
		$this->test_id = $test_id;
		$this->type    = $type;
	}

	/**
	 * Create a knowledge test result.
	 *
	 * @param string $test_id        Test identifier.
	 * @param float  $score          Score (0.0 or 1.0).
	 * @param string $model_answer   Model's response.
	 * @param string $correct_answer Expected answer.
	 * @param string $category       Test category.
	 *
	 * @return self
	 */
	public static function knowledge_result(
		string $test_id,
		float $score,
		string $model_answer,
		string $correct_answer,
		string $category = '',
	): self {
		$result                 = new self( $test_id, 'knowledge' );
		$result->score          = $score;
		$result->model_answer   = $model_answer;
		$result->correct_answer = $correct_answer;
		$result->category       = $category;

		return $result;
	}

	/**
	 * Create an execution test result.
	 *
	 * @param string               $test_id         Test identifier.
	 * @param string               $generated_code  Code generated by model.
	 * @param float                $static_score    Static analysis score.
	 * @param float                $runtime_score   Runtime verification score.
	 * @param float                $quality_score   AI judge quality score.
	 * @param array<string, mixed> $static_details  Static check details.
	 * @param array<string, mixed> $runtime_details Runtime check details.
	 * @param array<string, mixed> $judge_details   Judge evaluation details.
	 * @param string               $category        Test category.
	 *
	 * @return self
	 */
	public static function execution_result(
		string $test_id,
		string $generated_code,
		float $static_score,
		float $runtime_score,
		float $quality_score,
		array $static_details = [],
		array $runtime_details = [],
		array $judge_details = [],
		string $category = '',
	): self {
		$result                  = new self( $test_id, 'execution' );
		$result->generated_code  = $generated_code;
		$result->static_score    = $static_score;
		$result->runtime_score   = $runtime_score;
		$result->quality_score   = $quality_score;
		$result->static_details  = $static_details;
		$result->runtime_details = $runtime_details;
		$result->judge_details   = $judge_details;
		$result->category        = $category;

		return $result;
	}

	/**
	 * Create an error result.
	 *
	 * @param string $test_id  Test identifier.
	 * @param string $type     Test type.
	 * @param string $error    Error message.
	 * @param string $category Test category.
	 *
	 * @return self
	 */
	public static function error_result(
		string $test_id,
		string $type,
		string $error,
		string $category = '',
	): self {
		$result                = new self( $test_id, $type );
		$result->error         = $error;
		$result->score         = 0.0;
		$result->static_score  = 0.0;
		$result->runtime_score = 0.0;
		$result->quality_score = 0.0;
		$result->category      = $category;

		return $result;
	}

	/**
	 * Get the test ID.
	 *
	 * @return string
	 */
	public function get_test_id(): string {
		return $this->test_id;
	}

	/**
	 * Get the test type.
	 *
	 * @return string 'knowledge' or 'execution'
	 */
	public function get_type(): string {
		return $this->type;
	}

	/**
	 * Get the test category.
	 *
	 * @return string
	 */
	public function get_category(): string {
		return $this->category;
	}

	/**
	 * Get the knowledge test score.
	 *
	 * @return float Score between 0.0 and 1.0
	 */
	public function get_score(): float {
		return $this->score ?? 0.0;
	}

	/**
	 * Get the correctness score for execution tests.
	 *
	 * Combines static and runtime scores.
	 *
	 * @return float Score between 0.0 and 1.0
	 */
	public function get_correctness_score(): float {
		$static  = $this->static_score ?? 0.0;
		$runtime = $this->runtime_score ?? 0.0;

		return ( $static + $runtime ) / 2;
	}

	/**
	 * Get the quality score from AI judge.
	 *
	 * @return float Score between 0.0 and 1.0
	 */
	public function get_quality_score(): float {
		return $this->quality_score ?? 0.0;
	}

	/**
	 * Get the static analysis score.
	 *
	 * @return float|null Score or null if not applicable
	 */
	public function get_static_score(): ?float {
		return $this->static_score;
	}

	/**
	 * Get the runtime verification score.
	 *
	 * @return float|null Score or null if not applicable
	 */
	public function get_runtime_score(): ?float {
		return $this->runtime_score;
	}

	/**
	 * Get the generated code.
	 *
	 * @return string|null Code or null for knowledge tests
	 */
	public function get_generated_code(): ?string {
		return $this->generated_code;
	}

	/**
	 * Get the model's answer.
	 *
	 * @return string|null Answer or null for execution tests
	 */
	public function get_model_answer(): ?string {
		return $this->model_answer;
	}

	/**
	 * Get the correct answer.
	 *
	 * @return string|null Correct answer or null for execution tests
	 */
	public function get_correct_answer(): ?string {
		return $this->correct_answer;
	}

	/**
	 * Check if the test had an error.
	 *
	 * @return bool
	 */
	public function has_error(): bool {
		return $this->error !== null;
	}

	/**
	 * Get the error message.
	 *
	 * @return string|null Error message or null
	 */
	public function get_error(): ?string {
		return $this->error;
	}

	/**
	 * Get static check details.
	 *
	 * @return array<string, mixed>
	 */
	public function get_static_details(): array {
		return $this->static_details;
	}

	/**
	 * Get runtime check details.
	 *
	 * @return array<string, mixed>
	 */
	public function get_runtime_details(): array {
		return $this->runtime_details;
	}

	/**
	 * Get AI judge details.
	 *
	 * @return array<string, mixed>
	 */
	public function get_judge_details(): array {
		return $this->judge_details;
	}

	/**
	 * Get test duration in milliseconds.
	 *
	 * @return float
	 */
	public function get_duration_ms(): float {
		return $this->duration_ms;
	}

	/**
	 * Get the run number.
	 *
	 * @return int
	 */
	public function get_run_number(): int {
		return $this->run_number;
	}

	/**
	 * Set the run number.
	 *
	 * @param int $run Run number.
	 *
	 * @return self
	 */
	public function set_run_number( int $run ): self {
		$this->run_number = $run;
		return $this;
	}

	/**
	 * Set the test duration.
	 *
	 * @param float $ms Duration in milliseconds.
	 *
	 * @return self
	 */
	public function set_duration_ms( float $ms ): self {
		$this->duration_ms = $ms;
		return $this;
	}

	/**
	 * Set the category.
	 *
	 * @param string $category Test category.
	 *
	 * @return self
	 */
	public function set_category( string $category ): self {
		$this->category = $category;
		return $this;
	}

	/**
	 * Set additional metadata.
	 *
	 * @param array<string, mixed> $metadata Metadata array.
	 *
	 * @return self
	 */
	public function set_metadata( array $metadata ): self {
		$this->metadata = $metadata;
		return $this;
	}

	/**
	 * Convert to array for serialization.
	 *
	 * @return array<string, mixed>
	 */
	public function to_array(): array {
		$base = [
			'test_id'     => $this->test_id,
			'type'        => $this->type,
			'category'    => $this->category,
			'run_number'  => $this->run_number,
			'duration_ms' => $this->duration_ms,
			'error'       => $this->error,
		];

		if ( $this->type === 'knowledge' ) {
			return array_merge(
				$base,
				[
					'score'          => $this->score,
					'model_answer'   => $this->model_answer,
					'correct_answer' => $this->correct_answer,
				]
			);
		}

		return array_merge(
			$base,
			[
				'generated_code'    => $this->generated_code,
				'static_score'      => $this->static_score,
				'runtime_score'     => $this->runtime_score,
				'quality_score'     => $this->quality_score,
				'correctness_score' => $this->get_correctness_score(),
				'static_details'    => $this->static_details,
				'runtime_details'   => $this->runtime_details,
				'judge_details'     => $this->judge_details,
			]
		);
	}

	/**
	 * Convert to JSON string.
	 *
	 * @param int $flags JSON encode flags.
	 *
	 * @return string
	 */
	public function to_json( int $flags = 0 ): string {
		return wp_json_encode( $this->to_array(), $flags ) ?: '{}';
	}
}
